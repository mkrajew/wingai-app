"""Writes the template of the app, frontend/src/utils/poseTemplates.ts, from the shipped template (work/ship/templates.npy).

    python tools/pose/export_ts_template.py       (build_template.py makes templates.npy)

The numbers are written as the shortest text that gives the same float32, so the TypeScript file holds exactly what the reference used.
"""
import hashlib

import numpy as np

from config import POSES, REPO, WORK

OUT = REPO / "frontend" / "src" / "utils" / "poseTemplates.ts"
PER_LINE = 8


def number(v):
    return np.format_float_positional(np.float32(v), unique=True, trim="-")


def main():
    templates = np.load(WORK / "ship" / "templates.npy").astype(np.float32)
    assert templates.shape == (4, 768), templates.shape
    digest = hashlib.sha256(np.ascontiguousarray(templates).tobytes()).hexdigest()
    lines = [
        "// Generated by tools/pose/export_ts_template.py from tools/pose/work/ship/templates.npy. Do not edit by hand.",
        "//",
        "// The average wing in each of the four poses (in the order of POSE_TABLE of poseFromPixels.ts: " + ", ".join(POSES) + "),",
        "// as the descriptor that poseFromPixels.ts makes of a picture: 16 x 6 cells of 16 x 16 pixels, 8 direction bins,",
        "// the square root of the sum of the gradient magnitude in each bin (768 numbers). Made from the complete wings of 13 countries.",
        "",
        f'export const POSE_TEMPLATES_SHA256 = "{digest}";',
        "",
        "export const POSE_TEMPLATES: readonly (readonly number[])[] = [",
    ]
    for name, row in zip(POSES, templates):
        lines.append(f"  // {name}")
        lines.append("  [")
        for i in range(0, len(row), PER_LINE):
            lines.append("    " + ", ".join(number(v) for v in row[i : i + PER_LINE]) + ",")
        lines.append("  ],")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT} ({OUT.stat().st_size / 1024:.0f} KB), sha256 {digest}")


if __name__ == "__main__":
    main()
